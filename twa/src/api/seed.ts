function lesson(
  categoryId: string,
  order: number,
  title: string,
  description: string,
  options: Partial<Lesson> = {},
): Lesson {
  return {
    id: `${categoryId}-${order}`,
    categoryId,
    order,
    title,
    description,
    kinescopeId: '',
    durationSec: 540 + order * 65,
    free: false,
    moggsReward: 25,
    materialsUrl: materials,
    ...options,
  }
}

